-- Jalankan melalui Supabase SQL Editor.
-- Tidak ada nomor pengirim, raw SMS, atau secret pada kedua tabel.
CREATE TABLE IF NOT EXISTS public.lab_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL CHECK (device_id IN ('hp1', 'hp2')),
  demo_code TEXT NOT NULL CHECK (demo_code ~ '^[0-9]{6}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  request_hash TEXT NOT NULL UNIQUE CHECK (request_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX IF NOT EXISTS idx_lab_messages_device_date
  ON public.lab_messages (device_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.public_notices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL CHECK (device_id IN ('hp1', 'hp2')),
  notice_text TEXT NOT NULL CHECK (char_length(notice_text) BETWEEN 8 AND 140),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  request_hash TEXT NOT NULL UNIQUE CHECK (request_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX IF NOT EXISTS idx_public_notices_device_date
  ON public.public_notices (device_id, created_at DESC);

ALTER TABLE public.lab_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.public_notices ENABLE ROW LEVEL SECURITY;

